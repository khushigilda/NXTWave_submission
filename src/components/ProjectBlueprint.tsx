import { useState } from 'react';
import { Copy, Download, Check, AlertTriangle, ArrowRight, Lightbulb, Clock, Wrench } from 'lucide-react';
import type { GeneratedBlueprint } from '../storage';
import { trackEvent } from '../analytics';
import './ProjectBlueprint.css';

interface Props {
  blueprint: GeneratedBlueprint;
  category: string;
}

export default function ProjectBlueprint({ blueprint }: Props) {
  const [copied, setCopied] = useState(false);
  const [downloaded, setDownloaded] = useState(false);

  function buildMarkdown(): string {
    return `# ${blueprint.projectTitle}

> Generated by the 60-Minute Build Challenge (template-based, not a live AI API call)

## Problem Statement
${blueprint.problemStatement}

## Target User
${blueprint.targetUser}

## Proposed AI-Powered Solution
${blueprint.proposedSolution}

## Core Features (Top 3)
${blueprint.coreFeatures.map((f, i) => `${i + 1}. ${f}`).join('\n')}

## User Input & Expected Output
**Input:** ${blueprint.userInputDescription}
**Output:** ${blueprint.expectedOutputDescription}

## Simplest Useful First Version
${blueprint.simplestFirstVersion}

## Suggested Tools & Components
${blueprint.suggestedTools.map((t) => `- ${t}`).join('\n')}

## 60-Minute Build Plan
${blueprint.sixtyMinutePlan.map((step, i) => `${i + 1}. ${step}`).join('\n')}

## Starter Prompt
${blueprint.starterPrompt}

## One Limitation to Keep in Mind
${blueprint.limitation}

## Next Step
${blueprint.nextStep}

---
*Generated by the 60-Minute Build Challenge. This is a structured project template, not output from a live AI model.*
`;
  }

  async function handleCopy() {
    const text = buildMarkdown();
    try {
      await navigator.clipboard.writeText(text);
    } catch {
      const el = document.createElement('textarea');
      el.value = text;
      document.body.appendChild(el);
      el.select();
      document.execCommand('copy');
      document.body.removeChild(el);
    }
    setCopied(true);
    trackEvent('blueprint_copied');
    setTimeout(() => setCopied(false), 2500);
  }

  function handleDownload() {
    const text = buildMarkdown();
    const blob = new Blob([text], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${blueprint.projectTitle.replace(/\s+/g, '_').toLowerCase()}_blueprint.md`;
    a.click();
    URL.revokeObjectURL(url);
    setDownloaded(true);
    trackEvent('blueprint_downloaded');
    setTimeout(() => setDownloaded(false), 2500);
  }

  return (
    <div className="blueprint">
      {/* Header */}
      <div className="blueprint__header card">
        <div className="blueprint__header-top">
          <div>
            <span className="badge badge--success mb-3">Blueprint Ready</span>
            <h2 className="blueprint__title">{blueprint.projectTitle}</h2>
            <div className="prototype-notice mt-3">
              <span>ℹ️</span>
              <span>
                <strong>Note:</strong> This blueprint was generated using structured templates based on your inputs,
                not a live AI model call. It is specific to your problem but uses predefined patterns.
              </span>
            </div>
          </div>
          <div className="blueprint__actions">
            <button
              className={`btn ${copied ? 'btn--success' : 'btn--secondary'}`}
              onClick={handleCopy}
              id="copy-blueprint-btn"
              aria-label="Copy blueprint to clipboard"
            >
              {copied ? <Check size={16} /> : <Copy size={16} />}
              {copied ? 'Copied!' : 'Copy Blueprint'}
            </button>
            <button
              className={`btn ${downloaded ? 'btn--success' : 'btn--secondary'}`}
              onClick={handleDownload}
              id="download-blueprint-btn"
              aria-label="Download blueprint as Markdown file"
            >
              {downloaded ? <Check size={16} /> : <Download size={16} />}
              {downloaded ? 'Downloaded!' : 'Download Blueprint'}
            </button>
          </div>
        </div>
      </div>

      {/* Sections */}
      <div className="blueprint__grid">
        <BpSection icon="🎯" label="Problem Statement" color="primary">
          <p>{blueprint.problemStatement}</p>
        </BpSection>

        <BpSection icon="👤" label="Target User" color="info">
          <p>{blueprint.targetUser}</p>
        </BpSection>

        <BpSection icon="🤖" label="Proposed AI-Powered Solution" color="success" wide>
          <p>{blueprint.proposedSolution}</p>
        </BpSection>

        <BpSection icon="✨" label="Core Features (Top 3)" color="primary">
          <ol className="blueprint__list blueprint__list--numbered">
            {blueprint.coreFeatures.map((f, i) => <li key={i}>{f}</li>)}
          </ol>
        </BpSection>

        <BpSection icon="↔️" label="User Input & Expected Output" color="info">
          <div className="blueprint__io">
            <div className="blueprint__io-item">
              <span className="blueprint__io-label">Input</span>
              <span>{blueprint.userInputDescription}</span>
            </div>
            <div className="blueprint__io-arrow"><ArrowRight size={18} /></div>
            <div className="blueprint__io-item">
              <span className="blueprint__io-label">Output</span>
              <span>{blueprint.expectedOutputDescription}</span>
            </div>
          </div>
        </BpSection>

        <BpSection icon="🔧" label="Simplest Useful First Version" color="warning" wide>
          <p>{blueprint.simplestFirstVersion}</p>
        </BpSection>

        <BpSection icon={<Wrench size={16} />} label="Suggested Tools & Components" color="muted">
          <ul className="blueprint__list">
            {blueprint.suggestedTools.map((t, i) => <li key={i}>{t}</li>)}
          </ul>
        </BpSection>

        <BpSection icon={<Clock size={16} />} label="60-Minute Build Plan" color="accent">
          <ol className="blueprint__list blueprint__list--numbered blueprint__list--plan">
            {blueprint.sixtyMinutePlan.map((step, i) => <li key={i}>{step}</li>)}
          </ol>
        </BpSection>

        <BpSection icon={<Lightbulb size={16} />} label="Starter Prompt" color="success" wide>
          <div className="blueprint__prompt">{blueprint.starterPrompt}</div>
        </BpSection>

        <BpSection icon={<AlertTriangle size={16} />} label="One Limitation to Keep in Mind" color="warning">
          <p>{blueprint.limitation}</p>
        </BpSection>

        <BpSection icon="🚀" label="Next Step" color="primary">
          <p>{blueprint.nextStep}</p>
        </BpSection>
      </div>

      {/* Repeat actions at bottom */}
      <div className="blueprint__footer-actions">
        <button className={`btn ${copied ? 'btn--success' : 'btn--secondary'}`} onClick={handleCopy} id="copy-blueprint-btn-2">
          {copied ? <Check size={16} /> : <Copy size={16} />}
          {copied ? 'Copied!' : 'Copy Blueprint'}
        </button>
        <button className={`btn ${downloaded ? 'btn--success' : 'btn--secondary'}`} onClick={handleDownload} id="download-blueprint-btn-2">
          {downloaded ? <Check size={16} /> : <Download size={16} />}
          {downloaded ? 'Downloaded!' : 'Download .md File'}
        </button>
      </div>
    </div>
  );
}

const colorMap: Record<string, string> = {
  primary: 'var(--clr-primary)',
  info: 'var(--clr-info)',
  success: 'var(--clr-success)',
  warning: 'var(--clr-warning)',
  accent: 'var(--clr-accent)',
  muted: 'var(--clr-body-muted)',
};

const bgMap: Record<string, string> = {
  primary: 'var(--clr-primary-light)',
  info: 'var(--clr-info-light)',
  success: 'var(--clr-success-light)',
  warning: 'var(--clr-warning-light)',
  accent: 'var(--clr-accent-light)',
  muted: 'var(--clr-border)',
};

function BpSection({
  icon, label, color, children, wide,
}: {
  icon: React.ReactNode;
  label: string;
  color: string;
  children: React.ReactNode;
  wide?: boolean;
}) {
  return (
    <div className={`bp-section card${wide ? ' bp-section--wide' : ''}`}>
      <div className="bp-section__header" style={{ color: colorMap[color] }}>
        <span
          className="bp-section__icon"
          style={{ background: bgMap[color], color: colorMap[color] }}
        >
          {icon}
        </span>
        <span className="bp-section__label">{label}</span>
      </div>
      <div className="bp-section__content">{children}</div>
    </div>
  );
}
